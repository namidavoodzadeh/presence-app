// Generates next/engine/prompt_text.ts from the prompt files, so the engines carry their prompts as code and need no file
// reads at runtime (the hosted Edge Function bundle has no prompt files on disk). Run after editing any prompt:
//   deno run --allow-read --allow-write next/scripts/gen_prompts.ts          # write
//   deno run --allow-read next/scripts/gen_prompts.ts --check                # exit 1 when the module is out of date
const ROOT = new URL("../", import.meta.url);
export const PROMPT_FILES: Record<string, string> = {
  SAFETY_CLASSIFIER: "api/_shared/safety/prompt.md",
  TALK_TURN: "engine/talk/prompts/turn.md",
  TALK_REPAIR: "engine/talk/prompts/repair.md",
  TALK_FINISH: "engine/talk/prompts/finish.md",
  TALK_GUIDE: "engine/talk/prompts/guide.md",
  SIM_USER: "engine/sim/prompts/user.md",
  BRIDGE_ANALYSE: "engine/bridge/prompts/analyse.md",
  BRIDGE_REPAIR: "engine/bridge/prompts/repair.md",
  BRIDGE_REWRITE: "engine/bridge/prompts/rewrite.md",
  BRIDGE_VERIFY: "engine/bridge/prompts/verify.md",
  BRIDGE_REWORD: "engine/bridge/prompts/reword.md",
  BRIDGE_WHY: "engine/bridge/prompts/why.md",
  MIRROR_OBSERVE: "engine/mirror/prompts/observe.md",
  MIRROR_SYNTHESISE: "engine/mirror/prompts/synthesise.md",
  INSIGHT_COPY_JSON: "engine/bridge/insight_copy.json",
};
export const OUT = "engine/prompt_text.ts";

export async function render(): Promise<string> {
  const parts = ["// GENERATED by next/scripts/gen_prompts.ts from the prompt files named below. Do not edit; edit the .md and re-run.",
    "// The engines import these so the hosted bundle needs no file reads; a test keeps this module in step with the files.", ""];
  for (const [name, rel] of Object.entries(PROMPT_FILES)) {
    const text = await Deno.readTextFile(new URL(rel, ROOT));
    parts.push(`/** ${rel} */`, `export const ${name} = ${JSON.stringify(text)};`, "");
  }
  return parts.join("\n");
}

if (import.meta.main) {
  const want = await render();
  const target = new URL(OUT, ROOT);
  if (Deno.args.includes("--check")) {
    let have = "";
    try { have = await Deno.readTextFile(target); } catch { /* missing */ }
    if (have !== want) { console.error(`${OUT} is out of date; run deno task prompts`); Deno.exit(1); }
    console.log(`${OUT} up to date`);
  } else {
    await Deno.writeTextFile(target, want);
    console.log(`wrote ${OUT} (${Object.keys(PROMPT_FILES).length} files)`);
  }
}
